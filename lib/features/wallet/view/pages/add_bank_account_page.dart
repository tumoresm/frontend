  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: Colours.backgroundColor,
      appBar: AppBar(
        backgroundColor: Colours.backgroundColor,
        elevation: 0,
        title: const Text(
          'Add Bank Account',
          style: TextStyle(
            color: Colours.whiteColor,
            fontSize: 20,
            fontWeight: FontWeight.w600,
          ),
        ),
        leading: IconButton(
          onPressed: () => Navigator.pop(context),
          icon: const Icon(
            Symbols.arrow_back,
            color: Colours.whiteColor,
          ),
        ),
      ),
      body: Form(
        key: _formKey,
        child: SingleChildScrollView(
          padding: const EdgeInsets.all(16.0),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              // Info Card
              Container(
                padding: const EdgeInsets.all(16),
                decoration: BoxDecoration(
                  color: kPrimary.withOpacity(0.1),
                  borderRadius: BorderRadius.circular(12),
                  border: Border.all(
                    color: kPrimary.withOpacity(0.3),
                  ),
                ),
                child: Row(
                  children: [
                    const Icon(
                      Symbols.security,
                      color: kPrimary,
                      size: 24,
                    ),
                    const SizedBox(width: 12),
                    Expanded(
                      child: Text(
                        'Your bank account information is encrypted and secure. We use bank-level security to protect your data.',
                        style: TextStyle(
                          color: Colours.whiteColor.withOpacity(0.9),
                          fontSize: 14,
                        ),
                      ),
                    ),
                  ],
                ),
              ),
              
              const SizedBox(height: 24),
              
              // Bank Name
              TextFormField(
                controller: _bankNameController,
                style: const TextStyle(color: Colours.whiteColor),
                decoration: InputDecoration(
                  labelText: 'Bank Name *',
                  labelStyle: TextStyle(
                    color: Colours.whiteColor.withOpacity(0.7),
                  ),
                  prefixIcon: const Icon(
                    Symbols.account_balance,
                    color: kPrimary,
                  ),
                  border: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: BorderSide(
                      color: Colours.whiteColor.withOpacity(0.3),
                    ),
                  ),
                  enabledBorder: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: BorderSide(
                      color: Colours.whiteColor.withOpacity(0.3),
                    ),
                  ),
                  focusedBorder: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: const BorderSide(
                      color: kPrimary,
                      width: 2,
                    ),
                  ),
                ),
                validator: (value) {
                  if (value == null || value.trim().isEmpty) {
                    return 'Please enter bank name';
                  }
                  return null;
                },
              ),
              
              const SizedBox(height: 16),
              
              // Account Holder Name
              TextFormField(
                controller: _accountHolderController,
                style: const TextStyle(color: Colours.whiteColor),
                decoration: InputDecoration(
                  labelText: 'Account Holder Name *',
                  labelStyle: TextStyle(
                    color: Colours.whiteColor.withOpacity(0.7),
                  ),
                  prefixIcon: const Icon(
                    Symbols.person,
                    color: kPrimary,
                  ),
                  border: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: BorderSide(
                      color: Colours.whiteColor.withOpacity(0.3),
                    ),
                  ),
                  enabledBorder: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: BorderSide(
                      color: Colours.whiteColor.withOpacity(0.3),
                    ),
                  ),
                  focusedBorder: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: const BorderSide(
                      color: kPrimary,
                      width: 2,
                    ),
                  ),
                ),
                validator: (value) {
                  if (value == null || value.trim().isEmpty) {
                    return 'Please enter account holder name';
                  }
                  return null;
                },
              ),
              
              const SizedBox(height: 16),
              
              // Account Number
              TextFormField(
                controller: _accountNumberController,
                style: const TextStyle(color: Colours.whiteColor),
                decoration: InputDecoration(
                  labelText: 'Account Number *',
                  labelStyle: TextStyle(
                    color: Colours.whiteColor.withOpacity(0.7),
                  ),
                  prefixIcon: const Icon(
                    Symbols.numbers,
                    color: kPrimary,
                  ),
                  border: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: BorderSide(
                      color: Colours.whiteColor.withOpacity(0.3),
                    ),
                  ),
                  enabledBorder: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: BorderSide(
                      color: Colours.whiteColor.withOpacity(0.3),
                    ),
                  ),
                  focusedBorder: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
                    borderSide: const BorderSide(
                      color: kPrimary,
                      width: 2,
                    ),
                  ),
                ),
                keyboardType: TextInputType.number,
                validator: (value) {
                  if (value == null || value.trim().isEmpty) {
                    return 'Please enter account number';
                  }
                  if (value.length < 8) {
                    return 'Account number must be at least 8 digits';
                  }
                  return null;
                },
              ),
              

              
              const SizedBox(height: 16),
              
              // Routing Number
              TextFormField(
                controller: _routingNumberController,
                style: const TextStyle(color: Colours.whiteColor),
                decoration: InputDecoration(
                  labelText: 'Routing Number (optional)',
                  labelStyle: TextStyle(
                    color: Colours.whiteColor.withOpacity(0.7),
                  ),
                  prefixIcon: const Icon(
                    Symbols.route,
                    color: kPrimary,
                  ),
                  border: OutlineInputBorder(
                    borderRadius: BorderRadius.circular(12),
